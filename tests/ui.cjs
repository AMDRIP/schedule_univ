const http = require('http');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const esbuild = require('esbuild');
const { _electron } = require('playwright');

async function run() {
    const root = path.resolve(__dirname, '..');
    esbuild.buildSync({ entryPoints: ['tests/uiHarness.tsx'], bundle: true, outfile: '.test-output/ui-harness.js', platform: 'browser', external: ['bindings', 'fs', 'path', 'node-addon-api'] });
    esbuild.buildSync({ entryPoints: ['tests/fixtures.ts'], bundle: true, outfile: '.test-output/fixtures.cjs', platform: 'node', format: 'cjs' });
    const { makeFixture, config } = require('../.test-output/fixtures.cjs');
    const server = http.createServer((req, res) => {
        if (req.url === '/') { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end('<html><head><meta charset="utf-8"><link rel="stylesheet" href="/TWD/output.css"></head><body><div id="root"></div><script src="/.test-output/ui-harness.js"></script></body></html>'); return; }
        const filename = path.resolve(root, '.' + decodeURIComponent(req.url.split('?')[0]));
        if (!filename.startsWith(root + path.sep) || !fs.existsSync(filename) || !fs.statSync(filename).isFile()) { res.statusCode = 404; res.end(); return; }
        res.setHeader('Content-Type', filename.endsWith('.css') ? 'text/css' : 'text/javascript'); fs.createReadStream(filename).pipe(res);
    });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    let app;
    try {
        app = await _electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, 'ui-main.cjs')], env: { ...process.env, UNIV_TEST_URL: `http://127.0.0.1:${server.address().port}/` }, timeout: 30000 });
        const page = await app.firstWindow(); const errors = []; page.on('pageerror', error => errors.push(error.message));
        await page.waitForFunction(() => !!window.__store);
        const version = require('../package.json').version;
        await page.getByText(`Версия ${version}`, { exact: true }).waitFor();
        await page.evaluate(data => { window.__store.loadFullState(data); window.__enter(); }, makeFixture());
        await page.getByRole('link', { name: 'Работы и исследования', exact: true }).click();
        await page.getByRole('button', { name: 'Новая работа', exact: true }).click();
        const form = page.locator('form');
        await form.getByLabel('Вид работы').selectOption('coursework');
        await form.getByLabel('Обучающийся').fill('Иван Тестов');
        await form.getByLabel('Дисциплина / НИР').selectOption('subject');
        await form.getByLabel('Тема', { exact: true }).fill('Исследование методов оптимизации');
        await form.getByLabel(/^Научный руководитель/).selectOption('teacher');
        await page.getByRole('button', { name: 'Добавить этапы исследования', exact: true }).click();
        await page.screenshot({ path: '.test-output/work-editor-desktop.png', fullPage: true });
        await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
        await page.waitForFunction(() => window.__store.academicWorks.length === 1);
        const snapshot = await page.evaluate(() => window.__store.getFullState());
        assert.equal(snapshot.academicWorks[0].milestones.length, 5);
        assert.equal(snapshot.students.length, 1);
        assert.equal(snapshot.academicWorks[0].studentId, snapshot.students[0].id);
        await page.evaluate(data => window.__store.loadFullState(data), snapshot);
        await page.waitForFunction(() => window.__store.academicWorks[0]?.studentName === 'Иван Тестов');
        await page.screenshot({ path: '.test-output/work-register-desktop.png', fullPage: true });
        await page.setViewportSize({ width: 780, height: 1000 });
        await page.screenshot({ path: '.test-output/work-register-compact.png', fullPage: true });
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.getByTitle('Запланировать научное событие', { exact: true }).click();
        const eventDialog = page.getByRole('dialog', { name: 'Индивидуальное научное событие' });
        await eventDialog.getByLabel('Вид научного события').selectOption('defense');
        await eventDialog.getByRole('checkbox', { name: 'Резервный преподаватель' }).check();
        await eventDialog.getByRole('button', { name: 'Подобрать время', exact: true }).click();
        await eventDialog.getByText('Свободное время найдено', { exact: true }).waitFor();
        await eventDialog.getByRole('button', { name: 'Добавить в расписание', exact: true }).click();
        await page.waitForFunction(() => window.__store.schedule.some(entry => entry.academicWorkId && entry.additionalTeacherIds?.includes('reserve')));
        await page.getByRole('link', { name: 'Учебные планы', exact: true }).click();
        await page.getByRole('button', { name: 'Новая версия', exact: true }).click();
        const versionForm = page.getByRole('form', { name: 'Новая версия плана' });
        await versionForm.getByLabel('Название версии', { exact: true }).fill('Набор 2027');
        await versionForm.getByLabel('Набор', { exact: true }).fill('2027');
        await versionForm.getByLabel('Профиль', { exact: true }).fill('AI');
        await versionForm.getByRole('button', { name: 'Создать версию', exact: true }).click();
        await page.waitForFunction(() => window.__store.educationalPlans.length === 2);
        const versions = await page.evaluate(() => window.__store.educationalPlans);
        assert.equal(versions[0].entries[0].lectureHours, 2);
        assert.equal(versions[1].admissionYear, 2027);
        assert.equal(await page.getByLabel('Версия учебного плана', { exact: true }).inputValue(), versions[1].id);
        await page.getByRole('link', { name: 'Статистика', exact: true }).click();
        await page.getByRole('button', { name: 'Баланс часов', exact: true }).click();
        await page.getByRole('region', { name: 'Баланс плана и расписания' }).waitFor();
        const repairData = makeFixture();
        const lesson = { id: 'lesson', subjectId: 'subject', groupId: 'group', teacherId: 'teacher', classroomId: 'room', classType: 'Лекция', date: '2026-10-19', day: 'Понедельник', timeSlotId: 'first', deliveryMode: 'Очно', weekType: 'every' };
        repairData.schedule = [lesson, { ...lesson, id: 'conflict' }];
        await page.evaluate(data => window.__store.loadFullState(data), repairData);
        await page.waitForFunction(() => window.__store.schedule.some(entry => entry.id === 'conflict'));
        const original = await page.evaluate(() => JSON.stringify(window.__store.schedule));
        await page.evaluate(() => window.__store.quickRepairScheduleEntry('conflict'));
        const repairDialog = page.getByRole('dialog', { name: 'Предпросмотр исправления' });
        await repairDialog.waitFor();
        assert.equal(await page.evaluate(() => JSON.stringify(window.__store.schedule)), original);
        await repairDialog.getByRole('button', { name: 'Применить исправление', exact: true }).click();
        await page.waitForFunction(() => window.__store.canUndoRepair);
        assert.notEqual(await page.evaluate(() => JSON.stringify(window.__store.schedule)), original);
        await page.getByTitle('Отменить последний ремонт', { exact: true }).click();
        await page.waitForFunction(value => JSON.stringify(window.__store.schedule) === value, original);
        await page.evaluate(() => window.__store.quickRepairScheduleEntry('conflict'));
        await repairDialog.waitFor();
        await page.evaluate(() => window.__store.updateScheduleEntry({ ...window.__store.schedule[0], date: '2026-10-20', day: 'Вторник' }));
        await page.waitForFunction(() => window.__store.schedule[0].date === '2026-10-20');
        const staleRejected = await page.evaluate(() => { try { window.__store.applyScheduleRepair(); return false; } catch (error) { return error.message.includes('изменилось'); } });
        assert.equal(staleRejected, true);
        await page.evaluate(() => window.__store.dismissRepairPreview());
        const rejected = await page.evaluate(() => { try { window.__store.addScheduleEntry({ ...window.__store.schedule[0], date: '2026-10-20', day: 'Вторник', classroomId: 'missing' }); return false; } catch { return true; } });
        assert.equal(rejected, true);
        await page.getByRole('link', { name: 'Обучающиеся', exact: true }).click();
        await page.getByRole('button', { name: 'Обучающийся', exact: true }).click();
        const studentForm = page.getByRole('form', { name: 'Карточка обучающегося' });
        await studentForm.getByLabel('ФИО', { exact: true }).fill('Анна Тестова');
        await studentForm.getByRole('button', { name: 'Сохранить обучающегося', exact: true }).click();
        await page.waitForFunction(() => window.__store.students.some(student => student.name === 'Анна Тестова'));
        const substitutionData = makeFixture(); substitutionData.schedule = [lesson];
        substitutionData.teacherSubjectLinks.push({ ...substitutionData.teacherSubjectLinks[0], id: 'reserve-binding', teacherId: 'reserve' });
        await page.evaluate(data => window.__store.loadFullState(data), substitutionData);
        await page.waitForFunction(() => window.__store.schedule.length === 1 && !window.__store.resourceAbsences.length);
        await page.getByRole('link', { name: 'Оперативные замены', exact: true }).click();
        const substitutionForm = page.getByRole('form', { name: 'Подбор оперативных замен' });
        await substitutionForm.getByLabel('Причина', { exact: true }).fill('Больничный для автотеста');
        await substitutionForm.getByRole('button', { name: 'Подобрать замены', exact: true }).click();
        await page.getByText('Предпросмотр замен', { exact: true }).waitFor();
        await page.getByRole('button', { name: 'Применить замены', exact: true }).click();
        await page.waitForFunction(() => window.__store.substitutionLog.length === 1);
        assert.equal(await page.evaluate(() => window.__store.resourceAbsences[0].reason), 'Больничный для автотеста');
        const withLog = await page.evaluate(() => window.__store.getFullState());
        await page.evaluate(data => window.__store.loadFullState(data), withLog);
        await page.waitForFunction(() => window.__store.substitutionLog[0]?.absence?.reason === 'Больничный для автотеста');
        await page.evaluate(data => window.__store.loadFullState(data), makeFixture());
        await page.waitForFunction(() => window.__store.schedule.length === 0);
        await page.getByRole('link', { name: 'Статистика', exact: true }).click();
        await page.getByRole('button', { name: 'Что, если?', exact: true }).click();
        await page.getByLabel('Итерации пробного расчёта', { exact: true }).fill('2');
        await page.getByRole('button', { name: 'Запустить пробный расчёт', exact: true }).click();
        await page.getByTestId('what-if-result').waitFor();
        assert.equal(await page.evaluate(() => window.__store.schedule.length), 0);
        await page.evaluate(() => {
            const OriginalWorker = window.Worker; window.__poolStats = { active: 0, peak: 0, created: 0 };
            window.Worker = class extends OriginalWorker {
                constructor(...args) { super(...args); this.finished = false; window.__poolStats.active++; window.__poolStats.created++; window.__poolStats.peak = Math.max(window.__poolStats.peak, window.__poolStats.active); }
                terminate() { if (!this.finished) { this.finished = true; window.__poolStats.active--; } return super.terminate(); }
            };
        });
        const result = await page.evaluate(async configuration => window.__store.runScheduler('heuristic', configuration), { ...config, iterations: 4, parallelWorkers: 2 });
        assert.equal(result.scheduled, 5); assert.equal(result.unscheduled, 0);
        const pool = await page.evaluate(() => window.__poolStats);
        assert.equal(pool.peak, 2); assert.equal(pool.active, 0);
        await page.getByText('Генерация завершена.', { exact: true }).waitFor();
        await page.screenshot({ path: '.test-output/generation-desktop.png', fullPage: true });
        assert.deepEqual(errors, []);
        console.log('Electron UI: version, coursework/student CRUD, migration, individual defense, plan versions, balance, ranked repair/apply/undo/stale rejection, substitutions and persisted journal, isolated what-if trial, 2 concurrent workers for 4 iterations, automatic worker cleanup passed.');
    } finally {
        if (app) await app.close();
        await new Promise(resolve => server.close(resolve));
    }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
